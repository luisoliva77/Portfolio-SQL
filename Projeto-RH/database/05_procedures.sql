/* PROCEDURE DE REGISTRAR FALTA */

CREATE PROCEDURE REGISTRAR_FALTA
	   @ID_FUNCIONARIO INT,
	   @MOTIVO VARCHAR(50)
AS
BEGIN
		INSERT INTO FALTA (MOTIVO,DATA_FALTA,ID_FUNCIONARIO)
		VALUES (@MOTIVO,GETDATE(),@ID_FUNCIONARIO)
END
GO

EXEC REGISTRAR_FALTA 1,'Consulta médica'

/*  Procedure de Atualizar salário (histórico) */

CREATE PROCEDURE ATUALIZAR_SALARIO
	   @ID_FUNCIONARIO INT,
	   @NOVO_SALARIO DECIMAL(10,2)
AS
BEGIN
		UPDATE SALARIO
		SET DATA_FIM = GETDATE()
		WHERE ID_FUNCIONARIO = @ID_FUNCIONARIO
		AND DATA_FIM IS NULL
	    
		INSERT INTO SALARIO (DATA_INICIO,VALOR,ID_FUNCIONARIO)
		VALUES ( GETDATE(),@NOVO_SALARIO,@ID_FUNCIONARIO)
END
GO

EXEC ATUALIZAR_SALARIO 11,2800.00

