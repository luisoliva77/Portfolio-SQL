/* Procedure: Admitir funcionário*/

CREATE PROCEDURE ADMITIR_FUNC
	   @NOME VARCHAR(50),
	   @CPF VARCHAR(15),
	   @SEXO CHAR(1),
	   @DATA_NASCIMENTO DATE,
	   @EMAIL VARCHAR(50),
	   @STATUS VARCHAR(10),
	   @ID_CARGO INT,
	   @ID_DEPARTAMENTO INT,
	   @SALARIO DECIMAL(10,2),
	   @CIDADE VARCHAR(50),
	   @DATA_DEMISSAO DATE

AS
BEGIN
		INSERT INTO FUNCIONARIO(NOME,CPF,SEXO,DATA_NASCIMENTO,DATA_ADMISSAO,EMAIL,STATUS,ID_CARGO,ID_DEPARTAMENTO,CIDADE,DATA_DEMISSAO) 
		VALUES (@NOME,@CPF,@SEXO,@DATA_NASCIMENTO,GETDATE(),@EMAIL,@STATUS,@ID_CARGO,@ID_DEPARTAMENTO,@CIDADE,@DATA_DEMISSAO)

		DECLARE @ID_FUNC INT = SCOPE_IDENTITY()

		INSERT INTO SALARIO(DATA_INICIO,VALOR,ID_FUNCIONARIO)
		VALUES (GETDATE(),@SALARIO,@ID_FUNC)
END
GO